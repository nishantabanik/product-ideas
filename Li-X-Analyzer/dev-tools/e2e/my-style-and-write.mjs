import { chromium } from "playwright-core";
const S = process.argv[2] || "./shots";
import { mkdirSync } from "node:fs";
mkdirSync(S, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ["--no-sandbox"] });
const page = await b.newPage({ viewport: { width: 1360, height: 1200 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
const base = process.env.BASE || "http://localhost:3100";
await page.goto(base + "/login"); await page.fill("input[name=password]", "pw123");
await Promise.all([page.waitForURL(base + "/"), page.click("button")]);
await page.goto(base + "/studio/style");
const add = async (title, name, body) => {
  const card = page.locator(".card", { has: page.locator(`h2:has-text('${title}')`) });
  await card.locator("input.input >> nth=0").fill(name);
  await card.locator("textarea").first().fill(body);
  await card.locator("button:has-text('Add')").last().click();
  await page.waitForSelector(`.style-item strong:has-text('${name}')`, { timeout: 15000 });
};
await add("Our tone", "Warm and direct", "Friendly, plain and a little funny.");
await add("Our way of writing", "Short lines", "One idea per line. Sentences under 12 words.");
await add("Memory", "Who we are", "I lead a DevOps team in Berlin.");
await add("Our story formats", "The Friday lesson", "Open with one thing that went wrong this week. End with one rule.");
await add("Our writing formats", "Mini case study", "Four short parts: problem, try, result, lesson.");
await page.setInputFiles("input[aria-label='Skill files']", process.argv[3]);
await page.click("button:has-text('Upload skill files')");
await page.waitForSelector(".style-item strong:has-text('hook-skill')", { timeout: 15000 });
await page.screenshot({ path: `${S}/n-style.png`, fullPage: true });
console.log("items:", await page.locator(".style-item strong").allTextContents());
// write tab
await page.goto(base + "/studio/write");
console.log("our group first:", await page.locator(".write-formats h4").first().textContent());
await page.click(".write-formats button:has-text('The Friday lesson')");
console.log("style card text:", (await page.locator("text=Our style adds about").textContent()));
await page.check("label:has-text('hook-skill') input");
await page.selectOption("select >> nth=1", { label: "Mini case study (ours)" }).catch(async () => { await page.selectOption("select:has(option:has-text('Mini case study'))", { label: "Mini case study (ours)" }); });
await page.fill("textarea >> nth=0", "Why we made our deploys faster");
await page.click("button:has-text('Write the post')");
await page.waitForSelector(".write-out textarea", { timeout: 30000 });
await page.uncheck("label:has-text('Keep the English simple') input");
await page.click("button:has-text('Write the post')").catch(() => {});
await page.waitForTimeout(2500);
await page.screenshot({ path: `${S}/n-write2.png`, fullPage: true });
console.log("ERRORS", JSON.stringify(errors));
await b.close();
